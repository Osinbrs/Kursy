# (не включительно)

text = 'Python это круто!'
s = text [-7:-2]
print(s) # Вывод: крут
# Отрицательные инлдексы считаются с конца строки

text = "Привет, как дела?"
s = text [:6]
# Извлекаем первые 6 символов
print(s) #Вывод: Привет

text = "Это последние символы"
s = text [-5:]
print(s)
# Извлекаем последние 5 символов. Вывод: волы

text = "12345678"
s = text [:: 2]
print(s)
# Извлекаем каждый ВТОРОЙ символ Вывод: 1357

text = "Аргентина манит негра"
