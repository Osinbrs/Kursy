from os import name

# Склеивание строк
n = "Артем"
age = 19
print("Меня зовут " + n + ". Мне" + str(age) +  "лет.")

# Процентное форматирование
name = "Егор"
age = 35
print ("Меня зовут %s. Мне %d лет." % (name, age))

# Форматирование командрой format
name = "Владимир"
age = 45
print ("Меня зовут {}. Мне {} лет".format(name, age))

# F- СТРОКИ - самый лучший способ
name = "Григорий"
age = 55
print(f"Меня зовут {name}. Мне {age} лет.")
