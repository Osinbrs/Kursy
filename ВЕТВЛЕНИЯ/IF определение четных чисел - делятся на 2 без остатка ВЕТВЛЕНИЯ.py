'''Проверка возраста'''
n = int (input ('ВВедите возраст: '))
if 0 <= n < 18:
    print ('вы не совершеннолетний')
elif 18 <= n  < 70:
    print ('вы взрослый')
elif n >= 70 and n < 100:
    print ('Солидный возраст')
elif 100 <=  n < 120:
    print('Долгожитель')
elif 120 <=  n:
    print('Вы гигантская черепаха')