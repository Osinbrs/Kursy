s = input ('введите время годэ: ')
s = s.lower()
if s == 'лето':
     print (f'{s} - прекрастное время для отдыха на пляже')
elif s == 'осень':
    print(f'{s.capitalize()} - хорошее время для прогулок в парке')
elif s == 'зима':
    print('Катаемся на лыжах')
elif s == 'весня':
    print('Пробужденние природы')
else:
    print(f'(s) - это не время года!')